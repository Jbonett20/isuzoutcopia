<?php

@session_start();

/*
|--------------------------------------------------------------------------
| Usuario autenticado
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['UsrData'])) {

    header("Location: login");

    exit;
}

/*
|--------------------------------------------------------------------------
| Permisos
|--------------------------------------------------------------------------
*/

include_once __DIR__ . '/../../models/Permission.php';

/*
|--------------------------------------------------------------------------
| Roles de sesión
|--------------------------------------------------------------------------
*/

$sessionRoleIds = array_map(
    'intval',
    $_SESSION['UsrData']['rolids'] ?? []
);

/*
|--------------------------------------------------------------------------
| Compatibilidad con sistema viejo
|--------------------------------------------------------------------------
*/

if (
    empty($sessionRoleIds)
    && !empty($_SESSION['UsrData']['rolid'])
) {
    $sessionRoleIds = [
        (int) $_SESSION['UsrData']['rolid']
    ];
}

/*
|--------------------------------------------------------------------------
| Admin total
|--------------------------------------------------------------------------
*/

$isAdmin = in_array(
    1,
    $sessionRoleIds,
    true
);

/*
|--------------------------------------------------------------------------
| Permisos permitidos
|--------------------------------------------------------------------------
*/

$allowedPermissionCodes = Permission::obtenerCodigosPermitidos(
    $sessionRoleIds
);

/*
|--------------------------------------------------------------------------
| Páginas públicas autenticadas
|--------------------------------------------------------------------------
|
| Estas páginas no requieren permiso.
|
*/

$publicPages = [
    'index',
    'profile'
];

/*
|--------------------------------------------------------------------------
| Validación automática
|--------------------------------------------------------------------------
*/

if (isset($loc) && $loc !== '') {

    /*
    |--------------------------------------------------------------------------
    | Página pública
    |--------------------------------------------------------------------------
    */

    if (in_array($loc, $publicPages, true)) {
        return;
    }

    /*
    |--------------------------------------------------------------------------
    | Admin siempre entra
    |--------------------------------------------------------------------------
    */

    if ($isAdmin) {
        return;
    }

    /*
    |--------------------------------------------------------------------------
    | Validar permiso
    |--------------------------------------------------------------------------
    */

    $hasPermission = in_array(
        $loc,
        $allowedPermissionCodes,
        true
    );

    /*
    |--------------------------------------------------------------------------
    | Sin permiso
    |--------------------------------------------------------------------------
    */

    if (!$hasPermission) {

        header("Location: home");

        exit;
    }
}